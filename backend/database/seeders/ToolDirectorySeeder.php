/**
 * دليل الأدوات الهندسية — المحتوى الأولي لكل مساقات الخطة.
 *
 * لماذا seeder لا إدخال يدوي: القائمة خمسة وتسعون بندًا تتوزّع على سبعة
 * وأربعين مساقًا، وإدخالها من اللوحة مرة يعني إعادتها كاملة عند كل
 * قاعدة جديدة. وهي هنا مراجَعة في الـ diff بدل أن تكون صفوفًا صامتة.
 *
 * الإدخال بـ updateOrCreate على الاسم، والربط بـ sync — فتشغيلها
 * مرارًا لا يكرّر شيئًا، وتعديل سطر هنا يصحّح الصف عند التشغيل التالي.
 *
 * ما ليس هنا عمدًا: الأدوات الستّ المبنية داخل المنصة (جدول الحقيقة،
 * التبسيط البولي، محوّل أنظمة العد، مرجع Big-O، حاسبة الشبكات الفرعية،
 * قاموس المصطلحات). مصدرها tools-registry.js وصفحة المساق تدمجها في
 * القسم نفسه، فصفٌّ لها هنا يعني بطاقتين لأداة واحدة.
 *
 *     php artisan db:seed --class=ToolDirectorySeeder
 */
class ToolDirectorySeeder extends Seeder
{
    public function run(): void
    {
        $codes = Course::pluck('id', 'code');
        $missing = [];

        foreach ($this->tools() as $index => $tool) {
            $ids = [];

            foreach ($tool['courses'] as $code) {
                if (! isset($codes[$code])) {
                    $missing[$code] = true;

                    continue;
                }

                $ids[$codes[$code]] = ['sort_order' => count($ids)];
            }

            $record = Tool::updateOrCreate(
                ['name' => $tool['name']],
                [
                    'type' => $tool['type'],
                    'description' => $tool['description'],
                    'official_url' => $tool['url'] ?? null,
                    'video_url' => null,
                    'explanation' => $tool['explanation'] ?? null,
                    'is_active' => true,
                    'sort_order' => $index,
                ]
            );

            $record->courses()->sync($ids);
        }

        $this->command?->info('أدوات الدليل: '.Tool::count());

        if ($missing) {
            $this->command?->warn('رموز مساقات لم تُطابَق: '.implode('، ', array_keys($missing)));
        }
    }

    /*
     * حقل video_url متروك فارغًا في كل الصفوف: رابط شرح عربي لا يُكتب
     * إلا بعد مشاهدته، ورابط ميت في دليل أسوأ من خانة فارغة. يملؤه
     * المشرف من اللوحة أداةً أداة.
     */
    private function tools(): array
    {
        return array_merge(
            $this->firstYear(),
            $this->secondYear(),
            $this->thirdYear(),
            $this->fourthYear()
        );
    }

