/* المصطلحات المرتبطة بمساق. يُستدعى من صفحة المساق مستقبلًا. */
function glossaryForCourse(code) {
  const key = String(code || '').trim();

  if (!key) return [];

  return GLOSSARY.filter(
    term => term.courses.indexOf(key) !== -1
  );
}

/* بحث بسيط: إنجليزي أو عربي أو داخل الشرح. */
function glossarySearch(query) {
  const q = String(query || '').trim().toLowerCase();

  if (!q) return GLOSSARY;

  /* الشرح يُوطَّأ أيضًا: بدونه يجد "cache" ولا يجد "LIFO"، فيصير
     البحث حسّاسًا للحالة في موضع دون آخر. والعربية لا تتأثر. */
  return GLOSSARY.filter(term =>
    term.en.toLowerCase().indexOf(q) !== -1
    || term.ar.indexOf(q) !== -1
    || term.def.toLowerCase().indexOf(q) !== -1
  );
}

if (typeof window !== 'undefined') {
  window.PTCGlossary = {
    all: GLOSSARY,
    forCourse: glossaryForCourse,
    search: glossarySearch
  };
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    all: GLOSSARY,
    forCourse: glossaryForCourse,
    search: glossarySearch
  };
}
